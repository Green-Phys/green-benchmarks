#!/usr/bin/env python3
"""Walk systems/*/results/*.json and render RESULTS.md.

Output is deterministic — sorted by system, then observable, then
release tuple — so the committed RESULTS.md has stable diffs.
"""
from __future__ import annotations

import json
import sys
from collections import defaultdict
from pathlib import Path

from _lib import REPO_ROOT, iter_systems, load_manifest


def _load_results(system_dir: Path) -> dict[str, dict]:
    out: dict[str, dict] = {}
    for f in sorted((system_dir / "results").glob("*.json")):
        with open(f) as fh:
            out[f.stem] = json.load(fh)
    return out


def _fmt(val: float | None, units: str) -> str:
    if val is None:
        return "—"
    if abs(val) >= 1e-3 and abs(val) < 1e5:
        return f"{val:.6g} {units}"
    return f"{val:.4e} {units}"


def render() -> str:
    lines: list[str] = ["# RESULTS.md", ""]
    lines.append("Generated by `tools/collect.py`. Do not edit by hand.")
    lines.append("")

    for manifest_path in iter_systems():
        manifest = load_manifest(manifest_path)
        system_name = manifest["system"]["name"]
        results = _load_results(manifest_path.parent)
        releases = sorted(results.keys())

        lines.append(f"## {system_name}")
        lines.append("")
        if not releases:
            lines.append("_no results yet_")
            lines.append("")
            continue

        # observables table
        header = ["observable"] + releases
        lines.append("| " + " | ".join(header) + " |")
        lines.append("|" + "|".join(["---"] * len(header)) + "|")
        for obs in manifest["observables"]:
            row = [f"`{obs['id']}`"]
            for rel in releases:
                v = results[rel].get("observables", {}).get(obs["id"])
                row.append(_fmt(v, obs["units"]))
            lines.append("| " + " | ".join(row) + " |")
        lines.append("")

        # timings table — printed separately so it cannot be confused
        # with physical regressions
        timing_keys: set[str] = set()
        for rel in releases:
            timing_keys.update(results[rel].get("timings", {}).keys())
        if timing_keys:
            lines.append("**Timings**")
            lines.append("")
            header = ["timing (s)"] + releases
            lines.append("| " + " | ".join(header) + " |")
            lines.append("|" + "|".join(["---"] * len(header)) + "|")
            for tk in sorted(timing_keys):
                row = [f"`{tk}`"]
                for rel in releases:
                    v = results[rel].get("timings", {}).get(tk)
                    row.append("—" if v is None else f"{v:.3g}")
                lines.append("| " + " | ".join(row) + " |")
            lines.append("")

    return "\n".join(lines) + "\n"


def main() -> None:
    out = render()
    target = REPO_ROOT / "RESULTS.md"
    target.write_text(out)
    sys.stdout.write(out)


if __name__ == "__main__":
    main()
