#!/usr/bin/env python3
"""Walk systems/*/results/*.json and render RESULTS.md.

Output is deterministic — sorted by system, then observable, then
release tuple — so the committed RESULTS.md has stable diffs.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

from _lib import (REPO_ROOT, flatten_result, iter_systems, load_manifest,
                  observable_units)

# Fixed absolute precision for all reported results, in the observable's
RESULT_DECIMALS = 8


def _load_results(system_dir: Path) -> dict[str, dict]:
    out: dict[str, dict] = {}
    for f in sorted((system_dir / "results").glob("*.json")):
        with open(f) as fh:
            out[f.stem] = json.load(fh)
    return out


def _fmt(val: float | None, units: str) -> str:
    if val is None:
        return "—"
    if val == 0:
        val = 0.0  # normalize -0.0 so it doesn't print a stray minus sign
    return f"{val:.{RESULT_DECIMALS}f} {units}"


def render() -> str:
    lines: list[str] = ["# RESULTS.md", ""]
    lines.append("Generated by `tools/collect.py`. Do not edit by hand.")
    lines.append("")
    lines.append(
        f"Results are rounded to {RESULT_DECIMALS} decimal places in "
        "their own unit (Ha or eV), matching the GW/SCF convergence "
        "threshold (1e-7 Ha)."
    )
    lines.append("")

    for manifest_path in iter_systems():
        manifest = load_manifest(manifest_path)
        system_name = manifest["system"]["name"]
        results = _load_results(manifest_path.parent)
        releases = sorted(results.keys())

        lines.append(f"## {system_name}")
        lines.append("")

        if not releases:
            lines.append("_no results yet_")
            lines.append("")
            continue

        # flatten each release's result (schema 2 or 3) into method/key dicts
        flat = {rel: flatten_result(results[rel]) for rel in releases}

        # observables table (rows: method/observable)
        obs_keys = sorted({k for rel in releases for k in flat[rel][0]})
        if obs_keys:
            header = ["observable"] + releases
            lines.append("| " + " | ".join(header) + " |")
            lines.append("|" + "|".join(["---"] * len(header)) + "|")
            for key in obs_keys:
                units = observable_units(key.split("/")[-1])
                row = [f"`{key}`"]
                for rel in releases:
                    row.append(_fmt(flat[rel][0].get(key), units))
                lines.append("| " + " | ".join(row) + " |")
            lines.append("")

        # timings table — separate so it can't be confused with regressions
        tim_keys = sorted({k for rel in releases for k in flat[rel][1]})
        if tim_keys:
            lines.append("**Timings (s, first iter)**")
            lines.append("")
            header = ["timing"] + releases
            lines.append("| " + " | ".join(header) + " |")
            lines.append("|" + "|".join(["---"] * len(header)) + "|")
            for key in tim_keys:
                row = [f"`{key}`"]
                for rel in releases:
                    v = flat[rel][1].get(key)
                    row.append("—" if v is None else f"{v:.3g}")
                lines.append("| " + " | ".join(row) + " |")
            lines.append("")

    return "\n".join(lines) + "\n"


def main() -> None:
    out = render()
    target = REPO_ROOT / "RESULTS.md"
    target.write_text(out)
    sys.stdout.write(out)


if __name__ == "__main__":
    main()